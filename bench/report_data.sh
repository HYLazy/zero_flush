#!/bin/bash
# Run every analyzer over whatever runs exist so far and write the tables to
# bench/out/analysis/<name>.txt. Safe to run repeatedly while the campaign continues.
set -uo pipefail
cd "$(dirname "$0")"
A=out/analysis
mkdir -p "$A"
runs() { ls -d out/"$1"/*/ 2>/dev/null | while read -r d; do
           ls "$d"/*.summary.json >/dev/null 2>&1 && echo "$d"; done; }

for st in A B C D E G; do
  R=$(runs "$st")
  [ -z "$R" ] && continue
  echo "=== stage $st: $(echo "$R" | wc -l) completed runs"
  for cmd in ledger timeline overlap readcost parallel conflict memory batch space compare; do
    python3 analyze.py "$cmd" $R > "$A/${st}_${cmd}.txt" 2>&1
  done
done

# per-run detailed tables for the runs that carry the headline numbers
for r in out/A/50gb_fill_r1 out/A/50gb_overwrite out/A/100gb_fill_r5 out/A/100gb_overwrite; do
  [ -d "$r" ] || continue
  n=$(basename "$r")
  python3 analyze.py all "$r" > "$A/run_${n}.txt" 2>&1
done
# consolidated provenance: one line per completed run (argv + identity + headline results),
# joining the manifest with analyze.py's ledger so the committed file carries both the
# exact configuration and the measured numbers.
for st in A B C D E G; do
  [ -f out/$st/manifest.jsonl ] || continue
  python3 - "$st" "$A/${st}_runs.txt" <<'PYEOF'
import glob, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath('.')) or '.')
sys.path.insert(0, 'bench')
import analyze as A
st, outp = sys.argv[1], sys.argv[2]
runs = {}
for d in sorted(glob.glob(f'out/{st}/*/')):
    for p in A.rundir_paths(d):
        runs[os.path.basename(p)] = A.Run(p)
led = {r['run']: r for r in A.ledger(list(runs.values()), quiet=True)}
lines = [f"=== stage {st}: run identity, argv and headline results (generated by report_data.sh) ===",
         "run_id | bin_md5 | git | rc | U_GiB | SST_WA | device_WA | WA_L0base | thr_ops/s | argv"]
for line in open(f'out/{st}/manifest.jsonl'):
    d = json.loads(line)
    rid = d['run_id']
    cands = [n for n in runs if n == rid or n.startswith(rid + '.')]
    agg = {'U_gib': 0.0, 'WA_sst': None, 'WA_device': None, 'WA_L0base': None, 'throughput': 0.0, 'argv': ''}
    for n in cands:
        r = runs[n]
        L = led.get(n, {})
        if L.get('U_gib', 0) > agg['U_gib']:
            agg['U_gib'] = L['U_gib']
            agg['WA_sst'] = L.get('WA_sst')
            agg['WA_device'] = L.get('WA_device')
            agg['WA_L0base'] = L.get('WA_L0base')
            agg['throughput'] = r.summary.get('throughput_ops_s', 0.0)
        for c in glob.glob(os.path.dirname(r.prefix) + '/*.config.txt'):
            for l in open(c):
                if l.startswith('argv:') and len(l) > len(agg['argv']):
                    agg['argv'] = l[5:].strip()
    def f(v, p=3):
        return f"{v:.{p}f}" if isinstance(v, (int, float)) else 'n/a'
    lines.append(f"{rid} | {d.get('bin_md5','')[:8]} | {d.get('git_head','')} | {d.get('rc','')} | "
                 f"{f(agg['U_gib'],2)} | {f(agg['WA_sst'])} | {f(agg['WA_device'])} | "
                 f"{f(agg['WA_L0base'])} | {agg['throughput']:.0f} | {agg['argv']}")
open(outp, 'w').write('\n'.join(lines) + '\n')
PYEOF
done
echo "wrote $A"
ls -la "$A" | head -30
